import { fireEvent, render, screen } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import Markdown from "./Markdown";
import { reportTopic, planSteps } from "./report";
import { provenanceLine, verifiedStamp } from "./report";

describe("standalone report presentation", () => {
  it("puts concise synthesis before the full evidence trail", () => {
    const report = [
      "## Reader brief",
      "### Who",
      "- [real] Tim owns the change.",
      "### What",
      "- [observation] The cache changed.",
      "### Where",
      "- [real] Start at @[src/cache.py]:4.",
      "### Why",
      "- [speculation] A stale key is likely.",
      "## Who",
      "- [observation] Git names Tim.",
      "  - [real] The commit is anchored.",
    ].join("\n");

    expect(reportTopic(report, "who")).toEqual({
      synthesis: "- [real] Tim owns the change.",
      trail: "- [observation] Git names Tim.\n  - [real] The commit is anchored.",
    });
  });

  it("renders nested lists and makes source references openable and copyable", () => {
    const open = vi.fn();
    const copy = vi.fn();
    const { container } = render(
      <Markdown onOpenSource={open} onCopySource={copy}>
        {"- First\n  - Nested\n\nCheck @[src/cache.py]:4."}
      </Markdown>,
    );

    expect(container.querySelector("ul ul")?.textContent).toContain("Nested");
    fireEvent.click(screen.getByRole("button", { name: "@src/cache.py:4" }));
    fireEvent.click(screen.getByRole("button", { name: "Open in editor" }));
    expect(open).toHaveBeenCalledWith("src/cache.py", 4);
    fireEvent.click(screen.getByRole("button", { name: "@src/cache.py:4" }));
    fireEvent.click(screen.getByRole("button", { name: "Copy path" }));
    expect(copy).toHaveBeenCalledWith("src/cache.py", 4);
  });
});

describe("report provenance", () => {
  it("reads the mechanical verification stamp", () => {
    const stamp = verifiedStamp("<!-- tb:verified branch=tim%2FECS-4-position commit=abc1234 ts=2026-09-01T10%3A00%3A00%2B00%3A00 harness=pi provider=openai-codex model=gpt-5.6-sol -->\n# Report\n");
    expect(stamp).toEqual({ branch: "tim/ECS-4-position", commit: "abc1234", ts: "2026-09-01T10:00:00+00:00", harness: "pi", provider: "openai-codex", model: "gpt-5.6-sol" });
    expect(provenanceLine(stamp, "")).toContain("Verified at abc1234 on tim/ECS-4-position");
    expect(provenanceLine(stamp, "")).toContain("Generated by pi / openai-codex / gpt-5.6-sol");
    expect(verifiedStamp("# no stamp")).toBeNull();
    expect(provenanceLine(null, "2026-09-01T10:00:00+00:00")).toMatch(/^Recorded /);
  });
});



describe("plan steps", () => {
  const withPlan = "## Reader brief\n\n### Standing\n\n- [real] Next: fix the header first (a.h:7).\n\n### What\n\n- [real] Defect: duplicate constructor (a.cpp:21).\n\n### Checklist\n\n- [real] Missing: WorldPos3 (ticket).\n\n### Plan\n\n- [real] Step: remove the duplicate constructor (a.cpp:21).\n- [speculation] grounded — Step: run the build (check).\n\n## What\n\n- [observation] x (diff).\n";
  it("prefers the report's own plan", () => {
    const steps = planSteps(withPlan);
    expect(steps).toEqual(["[real] remove the duplicate constructor (a.cpp:21).", "[speculation] grounded — run the build (check)."]);
    expect(steps.derived).toBeUndefined();
  });
  it("derives a plan from next, defects, and unfinished items when there is none", () => {
    const steps = planSteps(withPlan.replace(/### Plan[\s\S]*?## What/, "## What"));
    expect(steps.derived).toBe(true);
    expect([...steps]).toEqual(["[real] fix the header first (a.h:7).", "[real] Fix: duplicate constructor (a.cpp:21).", "[real] Implement: WorldPos3 (ticket)."]);
  });
  it("bounds a derived plan to seven steps", () => {
    const defects = Array.from({ length: 10 }, (_, index) => `- [real] Defect: problem ${index + 1} (a.cpp:${index + 1}).`).join("\n");
    const steps = planSteps(`## Reader brief\n\n### What\n\n${defects}\n\n## What\n\n- [observation] x (diff).\n`);
    expect(steps).toHaveLength(7);
    expect(steps[6]).toBe("…and 4 more: see the Defect claims under What and the checklist below.");
  });
});
