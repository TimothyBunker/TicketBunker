"""The bunker layout (DESIGN.md §3.13).

The bunker is the instance directory — easily navigable the way .git is:
a fixed, well-known layout defined here and nowhere else. Knowing one bunker
means knowing them all; every piece of instance state is addressable by path.
"""

from __future__ import annotations

from pathlib import Path

TB_DIR = ".tb"

# Session-local material that must not be committed with the project repo.
# Patterns with a slash anchor to the .gitignore's own directory, but these
# must match inside every <ticket>_bunker/ — hence the **/ prefixes.
TB_GITIGNORE = """\
# TicketBunker local-only state — generated by tb init.
*.session.json
literal_pi_session.json
**/sessions/*.form.md
**/sessions/*.transcript.txt
**/observations/patches/
*.draft.md
sync_ledger.jsonl
"""

# How the bunker merges when branches carrying .tb/ come together: append-only
# logs union cleanly; the master is a generated artifact — keep ours and
# regenerate (tb init sets the 'ours' driver; the post-merge hook regens).
TB_GITATTRIBUTES = """\
# TicketBunker merge behavior — generated by tb init.
**/ledger.jsonl merge=union
**/inferences/inferences.jsonl merge=union
**/reports/master.md merge=ours
"""


def branch_slug(branch: str) -> str:
    return branch.replace("/", "__")


def find_root(start: Path | None = None) -> Path | None:
    """Walk up from `start` (default: cwd) to the nearest directory holding
    a .tb/ — the same discovery rule git uses for .git."""
    cur = (start or Path.cwd()).resolve()
    for candidate in [cur, *cur.parents]:
        if (candidate / TB_DIR).is_dir():
            return candidate
    return None


def bunkers_dir(project_root: Path) -> Path:
    return Path(project_root) / TB_DIR


def bunker_path(project_root: Path, ticket_id: str) -> Path:
    return bunkers_dir(project_root) / f"{ticket_id}_bunker"


def paths(bunker: Path) -> dict[str, Path]:
    bunker = Path(bunker)
    return {
        "root": bunker,
        "tb_md": bunker / "tb.md",
        "ticket": bunker / "ticket.json",
        "context": bunker / "context",
        "sessions": bunker / "sessions",
        "observations": bunker / "observations",
        "patches": bunker / "observations" / "patches",
        "inferences": bunker / "inferences",
        "inference_log": bunker / "inferences" / "inferences.jsonl",
        "ledger": bunker / "ledger.jsonl",
        "reports": bunker / "reports",
        "children": bunker / "reports" / "branches",
        "master": bunker / "reports" / "master.md",
    }


def session_config(bunker: Path, branch: str) -> Path:
    return paths(bunker)["sessions"] / f"{branch_slug(branch)}.json"


def session_form(bunker: Path, branch: str) -> Path:
    """The working copy of the report form an agent session fills in.
    A local draft — the shared artifact is the published component."""
    return paths(bunker)["sessions"] / f"{branch_slug(branch)}.form.md"


def session_transcript(bunker: Path, branch: str) -> Path:
    """The harness's captured output for a session — local diagnostic
    material, never synced."""
    return paths(bunker)["sessions"] / f"{branch_slug(branch)}.transcript.txt"


def child_report(bunker: Path, branch: str) -> Path:
    return paths(bunker)["children"] / f"{branch_slug(branch)}.md"


# The merge session occupies a reserved session slot named "merge". Ticket
# branches follow username/TICKET-name (§3.14) and so never slug to it, and
# the existing sessions/ ignore patterns cover its form and transcript.
MERGE_SESSION = "merge"


def merge_form(bunker: Path) -> Path:
    return session_form(bunker, MERGE_SESSION)


def merge_transcript(bunker: Path) -> Path:
    return session_transcript(bunker, MERGE_SESSION)


def init_dirs(bunker: Path) -> None:
    p = paths(bunker)
    for key in ("context", "sessions", "observations", "inferences", "children"):
        p[key].mkdir(parents=True, exist_ok=True)
